import Foundation

public enum VoiceFlySchema: String, Codable, CaseIterable, Identifiable {
  case pinyin, flypy, natural, microsoft, wubi, wubiPinyin
  public var id: String { rawValue }
  public var rimeID: String { "voicefly_" + rawValue }
  public var title: String {
    switch self {
    case .pinyin: return "全拼"
    case .flypy: return "小鹤双拼"
    case .natural: return "自然码双拼"
    case .microsoft: return "微软双拼"
    case .wubi: return "五笔 86"
    case .wubiPinyin: return "五笔与拼音混输"
    }
  }
}

public struct VoiceFlySettings: Codable, Equatable {
  public var version = 1
  public var schema: VoiceFlySchema = .pinyin
  public var voiceEnabled = true
  public var voiceKey = "control"
  public var spaceLearning = true
  public var personalLearning = true
  public var directSymbols = true
  public var preferBuiltinMicrophone = false
  public var candidateCount = 25
  public var simplified = true
  public var fullShape = false
  public var completedSetup = false
  public init() {}

  public func validate() throws {
    guard version == 1, ["control", "option"].contains(voiceKey),
          [5, 9, 25].contains(candidateCount) else {
      throw VoiceFlySettingsError.invalid("设置文件格式不正确，原文件已保留。")
    }
  }
}

public enum VoiceFlySettingsError: LocalizedError {
  case invalid(String)
  public var errorDescription: String? {
    switch self { case .invalid(let message): return message }
  }
}

public struct VoiceFlyPaths {
  public let home: URL
  public init(home: URL = FileManager.default.homeDirectoryForCurrentUser) { self.home = home }
  public var support: URL { home.appendingPathComponent("Library/Application Support/VoiceFly") }
  public var settings: URL { support.appendingPathComponent("settings.json") }
  public var words: URL { support.appendingPathComponent("Lexicon/personal_usage.json") }
  public var rime: URL { home.appendingPathComponent("Library/Rime-VoiceFly") }
  public var backups: URL { support.appendingPathComponent("Backups") }
  public var legacyWords: URL {
    home.appendingPathComponent("Library/Mobile Documents/com~apple~CloudDocs/AppConfig/RimeSync/VoiceFlypyLexicon/personal_usage.json")
  }
}

public struct VoiceFlySettingsStore {
  public let paths: VoiceFlyPaths
  public init(paths: VoiceFlyPaths = VoiceFlyPaths()) { self.paths = paths }
  public func load() throws -> VoiceFlySettings {
    guard FileManager.default.fileExists(atPath: paths.settings.path) else {
      var defaults = VoiceFlySettings()
      // Existing installations keep their familiar keyboard and shortcuts.
      if FileManager.default.fileExists(atPath: paths.rime.appendingPathComponent("double_pinyin_flypy.custom.yaml").path) {
        defaults.schema = .flypy
      }
      return defaults
    }
    let result = try JSONDecoder().decode(VoiceFlySettings.self, from: Data(contentsOf: paths.settings))
    try result.validate()
    return result
  }
  public func save(_ settings: VoiceFlySettings) throws {
    try settings.validate()
    try createPrivateDirectory(paths.support)
    try VoiceFlyFileLock.withLock(for: paths.settings, timeout: 2) {
      try rejectLink(paths.settings)
      if FileManager.default.fileExists(atPath: paths.settings.path) { _ = try load() }
      let encoder = JSONEncoder()
      encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
      try encoder.encode(settings).write(to: paths.settings, options: .atomic)
      try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: paths.settings.path)
    }
    if paths.home.standardizedFileURL == FileManager.default.homeDirectoryForCurrentUser.standardizedFileURL {
      DistributedNotificationCenter.default().postNotificationName(
        Notification.Name("com.simonli.voicefly.settings-changed"), object: nil,
        userInfo: nil, deliverImmediately: true)
    }
  }

  /// Only app-owned schema overrides are generated. Existing custom layouts
  /// and dictionaries remain available in the input method's scheme menu.
  public func prepareRime(_ settings: VoiceFlySettings) throws {
    try settings.validate()
    try createPrivateDirectory(paths.rime)
    for schema in VoiceFlySchema.allCases {
      var contents = """
      # Generated by Voice Fly Settings. Advanced personal config is separate.
      patch:
        "menu/page_size": \(settings.candidateCount)
        "menu/alternative_select_keys": "\(settings.candidateCount == 25 ? "12345" : "123456789")"
        "selector/row_size": \(settings.candidateCount == 25 ? 5 : settings.candidateCount)
        "selector/bindings/Tab": next_row
        "selector/bindings/Shift+Tab": previous_row
        "voicefly_words/user_dict": voicefly_words_\(schema.rawValue)
        "voicefly_words/dictionary": ""
        "voicefly_words/db_class": stabledb
        "voicefly_words/enable_completion": false
        "voicefly_words/enable_sentence": false
        "voicefly_words/initial_quality": 1
        "engine/translators/+":
          - table_translator@voicefly_words
      """ + "\n"
      if schema == .flypy {
        let legacy = paths.rime.appendingPathComponent("double_pinyin_flypy.custom.yaml")
        if FileManager.default.fileExists(atPath: legacy.path) {
          let base = try String(contentsOf: legacy, encoding: .utf8)
          guard base.range(of: "(?m)^patch:[ \\t]*(?:#.*)?$", options: .regularExpression) != nil else {
            throw VoiceFlySettingsError.invalid("旧小鹤配置格式较特殊，原配置已保留，请先检查高级配置。")
          }
          var merged = base.hasSuffix("\n") ? base : base + "\n"
          // Preserve dictionaries, translators, key bindings, punctuation and
          // formatting the existing user already customized. Only settings
          // owned by this window override matching scalar patch entries.
          for line in contents.components(separatedBy: "\n").dropFirst(2) where !line.isEmpty {
            if line.hasPrefix("  \""), let separator = line.range(of: "\":") {
              let key = String(line[..<separator.upperBound])
              let regex = try NSRegularExpression(pattern: "(?m)^" + NSRegularExpression.escapedPattern(for: key) + "[^\\n]*$")
              if regex.firstMatch(in: merged, range: NSRange(merged.startIndex..., in: merged)) != nil {
                merged = regex.stringByReplacingMatches(in: merged, range: NSRange(merged.startIndex..., in: merged), withTemplate: NSRegularExpression.escapedTemplate(for: line))
                continue
              }
            }
            merged += line + "\n"
          }
          contents = "# Voice Fly wrapper retaining this user's previous Flypy configuration.\n" + merged
        }
      }
      let destination = paths.rime.appendingPathComponent(schema.rimeID + ".custom.yaml")
      try rejectLink(destination)
      try contents.write(to: destination, atomically: true, encoding: .utf8)
    }
    let destination = paths.rime.appendingPathComponent("default.custom.yaml")
    try VoiceFlyFileLock.withLock(for: destination, timeout: 2) {
      try rejectLink(destination)
      var original = FileManager.default.fileExists(atPath: destination.path)
        ? try String(contentsOf: destination, encoding: .utf8) : "patch:\n"
      guard original.range(of: "(?m)^patch:\\s*(?:#.*)?$", options: .regularExpression) != nil else {
        throw VoiceFlySettingsError.invalid("现有输入方案配置较特殊，请先备份并在高级配置中设置 schema_list。原文件已保留。")
      }
      let retainsUserList = original.range(of: "(?m)^  (?:schema_list|\"schema_list\"):[ \t]*(?:#.*)?$", options: .regularExpression) != nil
      if original.contains("# Voice Fly managed schemes"), !retainsUserList, original.contains("\"schema_list/+\":") {
        original = original.replacingOccurrences(of: "\"schema_list/+\":", with: "schema_list:")
        try original.write(to: destination, atomically: true, encoding: .utf8)
      }
      if !original.contains("# Voice Fly managed schemes") {
        _ = try backupFile(destination, root: paths.backups)
        // A patch path with /+ appends our schemes without replacing a user's
        // existing schema_list. It is inserted immediately below patch:.
        let listKey = retainsUserList ? "\"schema_list/+\"" : "schema_list"
        let block = "\n  # Voice Fly managed schemes\n  " + listKey + ":\n" + VoiceFlySchema.allCases.map { "    - schema: \($0.rimeID)\n" }.joined()
        let expression = try NSRegularExpression(pattern: "(?m)^patch:[ \\t]*(?:#.*)?$")
        let range = NSRange(original.startIndex..., in: original)
        guard let match = expression.firstMatch(in: original, range: range),
              let end = Range(match.range, in: original)?.upperBound else { return }
        var updated = original
        updated.insert(contentsOf: block, at: end)
        try updated.write(to: destination, atomically: true, encoding: .utf8)
      }
    }
  }
}

func rejectLink(_ url: URL) throws {
  if (try? url.resourceValues(forKeys: [.isSymbolicLinkKey]))?.isSymbolicLink == true {
    throw VoiceFlySettingsError.invalid("文件是链接，已停止写入以保护原文件。")
  }
}

func createPrivateDirectory(_ url: URL) throws {
  try rejectLink(url)
  try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true,
                                         attributes: [.posixPermissions: 0o700])
}

@discardableResult
func backupFile(_ url: URL, root: URL) throws -> URL? {
  guard FileManager.default.fileExists(atPath: url.path) else { return nil }
  try rejectLink(url)
  try createPrivateDirectory(root)
  let destination = root.appendingPathComponent(UUID().uuidString + "-" + url.lastPathComponent)
  try FileManager.default.copyItem(at: url, to: destination)
  return destination
}

public struct VoiceFlyWord: Identifiable, Equatable {
  public var id: String { text }
  public let text: String
  public let pinyin: String
  public let selections: Int
  public let explicit: Int
}

public final class VoiceFlyWordManager {
  public let paths: VoiceFlyPaths
  private let codeMap: [String: [String: String]]
  private let readings: [String: String]
  private let allReadings: [String: [String]]
  public init(paths: VoiceFlyPaths = VoiceFlyPaths(), resources: URL? = nil) {
    self.paths = paths
    let url = resources?.appendingPathComponent("word-codes.json")
    let object = url.flatMap { try? Data(contentsOf: $0) }.flatMap {
      try? JSONSerialization.jsonObject(with: $0) as? [String: Any]
    }
    codeMap = object?["codes"] as? [String: [String: String]] ?? [:]
    readings = object?["readings"] as? [String: String] ?? [:]
    allReadings = object?["all_readings"] as? [String: [String]] ?? [:]
  }
  private func load() throws -> VoiceFlyPersonalUsageStore.Document {
    guard FileManager.default.fileExists(atPath: paths.words.path) else { return .init() }
    let data = try Data(contentsOf: paths.words)
    guard data.count <= 4 * 1024 * 1024 else { throw VoiceFlySettingsError.invalid("词库文件过大，原文件已保留。") }
    let document = try JSONDecoder().decode(VoiceFlyPersonalUsageStore.Document.self, from: data)
    try validate(document)
    return document
  }
  private func validate(_ document: VoiceFlyPersonalUsageStore.Document) throws {
    guard document.schema_version == "1.0.0", document.terms.count <= 10000 else {
      throw VoiceFlySettingsError.invalid("词库格式不支持，原文件已保留。")
    }
    for (text, term) in document.terms {
      guard (2...12).contains(text.count), !text.contains(where: { $0.isWhitespace }),
            !term.flypy_code.isEmpty, term.flypy_code.allSatisfy({ $0.isASCII && $0.isLetter }),
            term.explicit_count >= 0, term.selection_count >= 0 else {
        throw VoiceFlySettingsError.invalid("词库包含无效记录，原文件已保留。")
      }
      if let pinyin = term.pinyin {
        let tokens = pinyin.split(separator: " ")
        guard tokens.count == text.count,
              tokens.allSatisfy({ !$0.isEmpty && $0.allSatisfy { $0.isASCII && $0.isLetter } }) else {
          throw VoiceFlySettingsError.invalid("词库包含无效读音，原文件已保留。")
        }
      }
    }
  }
  public func list() throws -> [VoiceFlyWord] {
    try load().terms.map { text, term in
      VoiceFlyWord(text: text, pinyin: term.pinyin ?? pronunciation(text, canonicalCode: term.flypy_code), selections: term.selection_count, explicit: term.explicit_count)
    }.sorted { $0.text.localizedStandardCompare($1.text) == .orderedAscending }
  }
  public func pronunciation(_ text: String, canonicalCode: String? = nil) -> String {
    if let code = canonicalCode {
      for reading in allReadings[text] ?? [] {
        if reading.split(separator: " ").compactMap({ VoiceFlyFlypyCodeResolver.canonicalCode(forPinyin: String($0)) }).joined() == code { return reading }
      }
      if code.count == text.count * 2 {
        let keys = Array(code)
        let syllables = text.enumerated().compactMap { index, character in
          let pair = String(keys[(index * 2)..<(index * 2 + 2)])
          return (allReadings[String(character)] ?? []).first {
            VoiceFlyFlypyCodeResolver.canonicalCode(forPinyin: $0) == pair
          }
        }
        if syllables.count == text.count { return syllables.joined(separator: " ") }
      }
    }
    if let known = readings[text] { return known }
    // Apple's on-device romanizer handles characters absent from the bundled
    // dictionary. The user can correct a polyphonic reading before saving.
    let latin = text.applyingTransform(.mandarinToLatin, reverse: false) ?? text
    return latin.replacingOccurrences(of: "ü", with: "v").replacingOccurrences(of: "ǖ", with: "v").replacingOccurrences(of: "ǘ", with: "v").replacingOccurrences(of: "ǚ", with: "v").replacingOccurrences(of: "ǜ", with: "v").folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "en_US_POSIX"))
      .replacingOccurrences(of: "ü", with: "v")
  }
  public func put(text: String, pinyin: String) throws {
    let syllables = pinyin.lowercased().split(separator: " ").map(String.init)
    guard (2...12).contains(text.count), text.unicodeScalars.allSatisfy({
      (0x3400...0x9fff).contains($0.value) || (0x20000...0x323af).contains($0.value)
    }), syllables.count == text.count,
    syllables.allSatisfy({ !$0.isEmpty && $0.allSatisfy { $0.isASCII && $0.isLetter } }),
    syllables.allSatisfy({ VoiceFlyFlypyCodeResolver.canonicalCode(forPinyin: $0) != nil }) else {
      throw VoiceFlySettingsError.invalid("请输入 2–12 个汉字，读音按每字一个拼音，用空格分开，例如：人工智能 / ren gong zhi neng。")
    }
    let code = syllables.compactMap { VoiceFlyFlypyCodeResolver.canonicalCode(forPinyin: $0) }.joined()
    try change { document in
      var term = document.terms[text] ?? .init(flypy_code: code, selection_count: 0, explicit_count: 0, updated_at: "")
      term.flypy_code = code
      term.pinyin = syllables.joined(separator: " ")
      term.explicit_count = max(1, term.explicit_count)
      term.updated_at = ISO8601DateFormatter().string(from: Date())
      document.terms[text] = term
    }
  }
  public func remove(text: String) throws {
    // Delete the old app-owned Flypy overlay first so it cannot resurrect a
    // removed word during the next recognition refresh.
    let legacy = paths.rime.appendingPathComponent("voicefly_learned_phrases.txt")
    if FileManager.default.fileExists(atPath: legacy.path) {
      try VoiceFlyFileLock.withLock(for: legacy, timeout: 2) {
        try rejectLink(legacy)
        let contents = try String(contentsOf: legacy, encoding: .utf8)
        _ = try backupFile(legacy, root: paths.backups)
        let updated = contents.components(separatedBy: "\n").filter {
          $0.split(separator: "\t").first.map(String.init) != text
        }.joined(separator: "\n")
        try updated.write(to: legacy, atomically: true, encoding: .utf8)
      }
    }
    try change { $0.terms.removeValue(forKey: text) }
  }
  private func change(_ mutation: (inout VoiceFlyPersonalUsageStore.Document) throws -> Void) throws {
    try createPrivateDirectory(paths.words.deletingLastPathComponent())
    try VoiceFlyFileLock.withLock(for: paths.words, timeout: 2) {
      try rejectLink(paths.words)
      var document = try load()
      _ = try backupFile(paths.words, root: paths.backups)
      try mutation(&document)
      let encoder = JSONEncoder()
      encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
      try encoder.encode(document).write(to: paths.words, options: .atomic)
      try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: paths.words.path)
    }
    try regenerate()
    if paths.home.standardizedFileURL == FileManager.default.homeDirectoryForCurrentUser.standardizedFileURL {
      DistributedNotificationCenter.default().postNotificationName(VoiceFlyLearnedPhraseStore.changedNotification,
        object: nil, userInfo: ["generation": UUID().uuidString], deliverImmediately: true)
    }
  }
  public func regenerate() throws {
    try createPrivateDirectory(paths.rime)
    let document = try load()
    for schema in VoiceFlySchema.allCases {
      var lines = ["# Generated from the local shared Voice Fly lexicon."]
      for (text, term) in document.terms.sorted(by: { $0.key < $1.key }) where term.explicit_count > 0 {
        let pinyin = (term.pinyin ?? pronunciation(text, canonicalCode: term.flypy_code)).split(separator: " ").map(String.init)
        let code: String?
        switch schema {
        case .pinyin: code = pinyin.joined()
        case .flypy: code = term.flypy_code
        case .natural, .microsoft: code = convert(pinyin, scheme: schema.rawValue)
        case .wubi, .wubiPinyin: code = wubi(text)
        }
        if let code, !code.isEmpty { lines.append("\(text)\t\(code)\t200") }
        if schema == .wubiPinyin { lines.append("\(text)\t\(pinyin.joined())\t200") }
      }
      let url = paths.rime.appendingPathComponent("voicefly_words_" + schema.rawValue + ".txt")
      try rejectLink(url)
      try (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
    }
  }
  public func initializeLocalConfiguration() throws {
    try migrateLegacyInstallationIfNeeded()
    try migrateLegacyResourcesIfNeeded()
    try migrateLegacyIfNeeded()
    let store = VoiceFlySettingsStore(paths: paths)
    let settings = try store.load()
    try store.prepareRime(settings)
    try regenerate()
    try store.save(settings)
  }
  /// These old identifiers are used only to import an earlier installation.
  /// Never register or launch a component under the retired product name.
  public func migrateLegacyInstallationIfNeeded() throws {
    let fm = FileManager.default
    let oldSupport = paths.home.appendingPathComponent("Library/Application Support/VoiceFlypy")
    let oldRime = paths.home.appendingPathComponent("Library/Rime-VoiceFlypy")
    if !fm.fileExists(atPath: paths.rime.path), fm.fileExists(atPath: oldRime.path) {
      try rejectLink(oldRime)
      let staging = paths.rime.deletingLastPathComponent().appendingPathComponent(".VoiceFly-migration-" + UUID().uuidString)
      defer { try? fm.removeItem(at: staging) }
      try fm.createDirectory(at: staging, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
      for item in try fm.contentsOfDirectory(at: oldRime, includingPropertiesForKeys: nil) where !["build", "sync", "trash"].contains(item.lastPathComponent) {
        try rejectLink(item)
        let destination = staging.appendingPathComponent(item.lastPathComponent.replacingOccurrences(of: "voiceflypy", with: "voicefly").replacingOccurrences(of: "VoiceFlypy", with: "VoiceFly"))
        try fm.copyItem(at: item, to: destination)
        if ["yaml", "txt", "json"].contains(destination.pathExtension), let text = try? String(contentsOf: destination, encoding: .utf8) {
          let updated = text.replacingOccurrences(of: "voiceflypy", with: "voicefly").replacingOccurrences(of: "VoiceFlypy", with: "VoiceFly")
          if text != updated { try updated.write(to: destination, atomically: true, encoding: .utf8) }
        }
      }
      try fm.moveItem(at: staging, to: paths.rime)
    }
    for name in ["Lexicon", "settings.json"] {
      let source = oldSupport.appendingPathComponent(name), destination = paths.support.appendingPathComponent(name)
      if fm.fileExists(atPath: source.path), !fm.fileExists(atPath: destination.path) {
        try rejectLink(source); try createPrivateDirectory(paths.support)
        try fm.copyItem(at: source, to: destination)
      }
    }
  }
  /// Existing installations may have private normalization rules in their
  /// former iCloud profile or old service bundle. Copy only named data files,
  /// once, to local user storage. These sources are never build inputs.
  public func migrateLegacyResourcesIfNeeded() throws {
    let cloud = paths.legacyWords.deletingLastPathComponent()
    let oldResources = paths.home.appendingPathComponent("Applications/VoiceFlypyService.app/Contents/Resources")
    let local = paths.words.deletingLastPathComponent()
    for name in ["hotwords.txt", "voice_rules.json", "domain_dict.txt", "engineering_symbol_aliases.tsv", "spoken_number_exceptions.txt"] {
      let destination = local.appendingPathComponent(name)
      guard !FileManager.default.fileExists(atPath: destination.path) else { continue }
      var candidates = [cloud.appendingPathComponent(name), cloud.appendingPathComponent("voice/" + name),
                        cloud.appendingPathComponent("speech/" + name), oldResources.appendingPathComponent("lexicon/" + name)]
      if name == "domain_dict.txt" { candidates.insert(cloud.deletingLastPathComponent().appendingPathComponent(name), at: 0); candidates.append(oldResources.appendingPathComponent(name)) }
      guard let source = candidates.first(where: {
        (try? $0.resourceValues(forKeys: [.isRegularFileKey]))?.isRegularFile == true
      }) else { continue }
      let data = try Data(contentsOf: source)
      guard data.count <= 4 * 1024 * 1024 else { throw VoiceFlySettingsError.invalid("旧词库过大，请先手动备份迁移。") }
      try createPrivateDirectory(local)
      try rejectLink(destination)
      try data.write(to: destination, options: .atomic)
      try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: destination.path)
    }
  }
  private func convert(_ pinyin: [String], scheme: String) -> String? {
    let codes = pinyin.compactMap { codeMap[scheme]?[$0] }
    return codes.count == pinyin.count ? codes.joined() : nil
  }
  private func wubi(_ text: String) -> String? {
    if let code = codeMap["wubi"]?[text] { return code }
    let chars = text.map { codeMap["wubi"]?[String($0)] }
    guard chars.allSatisfy({ $0 != nil }) else { return nil }
    let codes = chars.compactMap { $0 }
    if codes.count == 2 { return codes.map { String($0.prefix(2)) }.joined() }
    if codes.count == 3 { return String(codes[0].prefix(1)) + String(codes[1].prefix(1)) + String(codes[2].prefix(2)) }
    return codes.prefix(3).map { String($0.prefix(1)) }.joined() + String(codes.last!.prefix(1))
  }
  public func export(to url: URL) throws {
    let encoder = JSONEncoder(); encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
    try encoder.encode(load()).write(to: url, options: .atomic)
  }
  public func importWords(from url: URL) throws {
    let data = try Data(contentsOf: url)
    guard data.count <= 4 * 1024 * 1024 else { throw VoiceFlySettingsError.invalid("词库文件过大。") }
    let imported = try JSONDecoder().decode(VoiceFlyPersonalUsageStore.Document.self, from: data)
    try validate(imported)
    try change { document in
      for (text, term) in imported.terms where document.terms[text] == nil { document.terms[text] = term }
    }
  }
  /// Copy once from the old iCloud location. All future writes stay local;
  /// an inaccessible iCloud file never replaces an existing local ledger.
  public func migrateLegacyIfNeeded() throws {
    guard !FileManager.default.fileExists(atPath: paths.words.path),
          FileManager.default.fileExists(atPath: paths.legacyWords.path) else { return }
    try importWords(from: paths.legacyWords)
  }
}
